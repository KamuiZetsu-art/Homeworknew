def load_all_data():
    print("🚀 Начинаем загрузку данных...\n")

    print("📚 Загрузка групп...")
    count = 0
    for name, specialty in GROUPS.items():
        if db.add_group(name, specialty=specialty):
            count += 1
    print(f"   ✅ Добавлено: {count} групп\n")

    print("👨‍🏫 Загрузка преподавателей...")
    count = 0
    for full_name, short_name in TEACHERS:
        if db.add_teacher(full_name, short_name):
            count += 1
    print(f"   ✅ Добавлено: {count} преподавателей\n")

    print("📖 Загрузка предметов...")
    count = 0
    for name in SUBJECTS:
        if db.add_subject(name):
            count += 1
    print(f"   ✅ Добавлено: {count} предметов\n")

    print("🚪 Загрузка кабинетов...")
    count = 0
    for number in ROOMS:
        if db.add_room(number):
            count += 1
    print(f"   ✅ Добавлено: {count} кабинетов\n")

    print("=" * 50)
    print("✅ ЗАГРУЗКА ЗАВЕРШЕНА!")
    print("=" * 50)
    stats = db.get_overall_stats()
    print(f"📚 Групп: {stats['groups']}")
    print(f"👨‍🏫 Преподавателей: {stats['teachers']}")
    print(f"📖 Предметов: {stats['subjects']}")
    print(f"🚪 Кабинетов: {stats['rooms']}")


